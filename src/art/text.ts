/** 取字形点阵（未知字符返回 `null`）。 */
export function glyphBits(ch: string): readonly string[] | null {
  const bits = GLYPHS[ch];
  if (!bits) return null;
  const rows: string[] = [];
  for (let r = 0; r < GLYPH_H; r++) rows.push(bits.slice(r * GLYPH_W, (r + 1) * GLYPH_W));
  return rows;
}

/** 文本像素宽度（不含尾部 1px 间隔）。 */
export function textWidth(text: string, scale = 1): number {
  if (text.length === 0) return 0;
  return text.length * GLYPH_ADVANCE * scale - scale;
}

/** 文本像素高度。 */
export function textHeight(scale = 1): number {
  return GLYPH_H * scale;
}

/**
 * 在画布上画一行文本（整数坐标 + 整数倍缩放，零抗锯齿）。
 * 返回下一个可落笔的 x（便于连续排版）。
 */
export function drawText(
  canvas: PixelCanvas,
  x: number,
  y: number,
  text: string,
  color: Rgba,
  scale = 1,
): number {
  const s = Math.max(1, Math.round(scale));
  let cx = Math.round(x);
  for (const ch of text) {
    const rows = glyphBits(ch);
    if (rows === null) {
      // 缺字：画空心方框，让问题在接触表上直接可见（而不是静默留白）。
      for (let r = 0; r < GLYPH_H; r++) {
        for (let c = 0; c < GLYPH_W; c++) {
          const edge = r === 0 || r === GLYPH_H - 1 || c === 0 || c === GLYPH_W - 1;
          if (edge) canvas.fillRect(cx + c * s, y + r * s, s, s, color);
        }
      }
    } else {
      for (let r = 0; r < GLYPH_H; r++) {
        const row = rows[r]!;
        for (let c = 0; c < GLYPH_W; c++) {
          if (row[c] === '1') canvas.fillRect(cx + c * s, y + r * s, s, s, color);
        }
      }
    }
    cx += GLYPH_ADVANCE * s;
  }
  return cx;
}

/** 以 `cx` 为中心画一行文本。 */
export function drawTextCentered(
  canvas: PixelCanvas,
  cx: number,
  y: number,
  text: string,
  color: Rgba,
  scale = 1,
): void {
  drawText(canvas, Math.round(cx - textWidth(text, scale) / 2), y, text, color, scale);
}

/**
 * 按最大字符数折行（**按空格优先，其次硬折**）。
 * 接触表里的属性串可能很长，需要保证不越出单元格。
 */
export function wrapText(text: string, maxChars: number): string[] {
  if (maxChars <= 0) return [text];
  const out: string[] = [];
  for (const raw of text.split('\n')) {
    let line = '';
    for (const word of raw.split(' ')) {
      if (word.length > maxChars) {
        if (line.length > 0) {
          out.push(line);
          line = '';
        }
        let rest = word;
        while (rest.length > maxChars) {
          out.push(rest.slice(0, maxChars));
          rest = rest.slice(maxChars);
        }
        line = rest;
        continue;
      }
      const candidate = line.length === 0 ? word : `${line} ${word}`;
      if (candidate.length > maxChars) {
        out.push(line);
        line = word;
      } else {
        line = candidate;
      }
    }
    out.push(line);
  }
  return out;
}
